def zh_ko(s):
    """문자열 안의 중국어 표현을 사전대로 치환한다."""
    if not s:
        return s
    for zh, ko in _PAIRS:
        if zh in s:
            s = s.replace(zh, ko)
    return s

def leftover(s):
    """치환 후 남은 간체 문자를 돌려준다 (0이어야 통과)."""
    return re.findall(r'[一-鿿]', s or '')

def audit(strings):
    """미등록 중국어 표현 목록 — 사전에 추가할 후보."""
    left = {}
    for s in strings:
        t = zh_ko(s)
        if re.search(r'[一-鿿]', t):
            left[s] = t
    return left
