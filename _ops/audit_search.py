import io, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

s = io.open(os.path.join(ROOT, 'product', 'index.html'), encoding='utf-8').read()
seg = s.split('<!--ALLPROD_START-->')[1].split('<!--ALLPROD_END-->')[0]
