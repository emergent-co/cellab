IDX = [((it.get('t', '') + ' ' + it.get('k', '') + ' ' + it.get('c', '')).lower(), it.get('u', ''))
       for it in idx]


def norm(x):
    import re as _r
    return _r.sub(r'[\s\u00b7\-_/()]', '', x.lower().replace('\u2103', '도'))


def hit(rows, q):
    ws = [w for w in q.lower().split() if w]
    out = []
    for hay, u in rows:
        hn = norm(hay)
        if all((w in hay) or (norm(w) in hn) for w in ws):
            out.append(u)
    return out


