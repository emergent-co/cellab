def main():
    print('카탈로그 카드 %d장 · 검색인덱스 %d건\n' % (len(CARDS), len(IDX)))
    bad_cat, bad_idx, weak = [], [], []
    for q, need, memo in Q:
        c = len(hit(CARDS, q))
        i = len(hit(IDX, q))
        flag = ''
        if need and c == 0:
            bad_cat.append((q, c, i, memo)); flag = ' [카탈로그 0]'
        elif need and c < need:
            weak.append((q, c, i, need, memo)); flag = ' [카탈로그 %d<%d]' % (c, need)
        if need and i == 0:
            bad_idx.append((q, c, i, memo)); flag += ' [헤더 0]'
        print('%-18s 카탈로그 %3d · 헤더 %3d%s' % (q, c, i, flag))

    print('\n' + '=' * 60)
    print('카탈로그 0건 (%d):' % len(bad_cat))
    for q, c, i, m in bad_cat:
        print('   %-18s 헤더는 %d건 %s' % (q, i, m))
    print('\n헤더 0건 (%d):' % len(bad_idx))
    for q, c, i, m in bad_idx:
        print('   %-18s 카탈로그는 %d건 %s' % (q, c, m))
    print('\n건수 부족 (%d):' % len(weak))
    for q, c, i, n, m in weak:
        print('   %-18s 카탈로그 %d (기대 %d+) · 헤더 %d' % (q, c, n, i))


