def floor(slug, rows):
    """(모델, 규격, 산출가) → 가오스 −5,000원 하한을 적용한 행"""
    m = GAOSS.get(slug, {})
    out = []
    for model, spec, p in rows:
        g = m.get(model)
        if p and g and g[0]:
            p = max(p, int(round((g[0] - GAP) / 1000.0)) * 1000)
        out.append((model, spec, p))
    return out

def report(slug, rows):
    """조정 내역 — 콘솔 확인용"""
    m = GAOSS.get(slug, {})
    lines = []
    for model, spec, p in rows:
        g = m.get(model)
        if p and g and g[0]:
            f = int(round((g[0] - GAP) / 1000.0)) * 1000
            if f > p:
                lines.append('   %-16s %10s → %10s  (가오스 %s %s)'
                             % (model, format(p, ','), format(f, ','),
                                format(g[0], ','), g[1]))
    return lines
