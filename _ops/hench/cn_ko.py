def val(v):
    """번역 결과. 한자가 남으면 None(사양표에서 제외)."""
    v = (v or '').strip()
    while v.endswith('模具'):
        v = v[:-2].strip()
    if not v:
        return None
    for a, b in _PRE:
        v = v.replace(a, b)
    v = v.strip()
    if not v:
        return None
    if v in V:
        return V[v]
    m = re.match(r'^([A-Z][A-Za-z0-9\-/\.]{1,18})\s*[一-鿿]', v)
    if m:
        return m.group(1)
    s = v
    for a, b in _UNIT:
        s = s.replace(a, b)
    s = s.replace('根', '주')
    if re.search(r'[一-鿿]', s):
        return None
    s = re.sub(r'\s+', ' ', s).strip()
    s = re.sub(r'\s*[（(]\s*[MNDdT]\s*[）)]\s*$', '', s)
    if '·' in s:
        seen, keep = set(), []
        for x in [y.strip() for y in s.split('·')]:
            if x and x not in seen:
                seen.add(x)
                keep.append(x)
        s = ' · '.join(keep)
    return s


